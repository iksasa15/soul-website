// Generates src/components/globe/land-mask.ts: one bit per Fibonacci-sphere point
// (1 = land). The globe regenerates the same points at runtime, so only the mask ships.
// Run: node scripts/generate-land-mask.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

export const POINT_COUNT = 36000;
const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url)));
const land = feature(topo, topo.objects.land);

const golden = Math.PI * (3 - Math.sqrt(5));
const bytes = new Uint8Array(Math.ceil(POINT_COUNT / 8));
let count = 0;
for (let i = 0; i < POINT_COUNT; i++) {
  const y = 1 - (i / (POINT_COUNT - 1)) * 2;
  const r = Math.sqrt(1 - y * y);
  const t = golden * i;
  const x = Math.cos(t) * r;
  const z = Math.sin(t) * r;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lng = (Math.atan2(-z, x) * 180) / Math.PI;
  if (geoContains(land, [lng, lat])) {
    bytes[i >> 3] |= 1 << (i & 7);
    count++;
  }
}
const b64 = Buffer.from(bytes).toString("base64");
writeFileSync(
  new URL("../src/components/globe/land-mask.ts", import.meta.url),
  `// Auto-generated by scripts/generate-land-mask.mjs — do not edit.\n` +
    `export const LAND_POINT_COUNT = ${POINT_COUNT};\n` +
    `export const LAND_MASK_BASE64 =\n  "${b64}";\n`,
);
console.log(`land points: ${count} / ${POINT_COUNT}, mask ${b64.length} chars`);
